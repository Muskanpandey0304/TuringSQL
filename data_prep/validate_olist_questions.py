"""Validate the Olist benchmark questions and write a human review file.

Checks every question: required fields, unique ids, the gold SQL passes the safety check and returns
rows, order_matters agrees with the gold ORDER BY, and a top-N (ORDER BY ... LIMIT n) has no tie
exactly at the cut-off (a tie would make the "right" answer depend on arbitrary ordering).

Usage:
    python data_prep/validate_olist_questions.py                 # validate + write questions_review.md
    python data_prep/validate_olist_questions.py --split         # also write questions_dev/test.json

The split is stratified by level with a fixed seed: one third of each level goes to dev.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from collections import Counter
from pathlib import Path

from sqlglot import exp

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from turingsql.safety import check_sql, execute_readonly  # noqa: E402

OLIST = ROOT / "data" / "olist"
DB = OLIST / "olist_marts.db"
DRAFT = OLIST / "questions_draft.json"
LEVELS = ("easy", "medium", "hard", "definition")
REQUIRED = ("id", "level", "question", "gold_sql", "order_matters")
SPLIT_SEED = 20261124


def limit_tie(sql: str) -> str | None:
    """If the query is ORDER BY ... LIMIT n, report a tie between row n and row n+1 on the sort keys."""
    tree = check_sql(sql)
    limit = tree.args.get("limit")
    order = tree.args.get("order")
    if limit is None or order is None:
        return None
    n = int(limit.expression.name)
    # Re-select the ORDER BY expressions without the LIMIT and compare positions n-1 and n.
    unlimited = tree.copy()
    unlimited.set("limit", None)
    keys = [o.this for o in order.expressions]
    alias_map = {s.alias_or_name: s for s in unlimited.expressions}
    key_exprs = [
        alias_map[k.name].unalias().copy() if isinstance(k, exp.Column) and k.name in alias_map and not k.table
        else k.copy()
        for k in keys
    ]
    unlimited.set("expressions", [*unlimited.expressions, *[e.as_(f"_k{i}") for i, e in enumerate(key_exprs)]])
    rows = execute_readonly(DB, unlimited.sql(dialect="sqlite"), max_rows=n + 1)
    if len(rows) <= n:
        return None
    width = len(key_exprs)
    if rows[n - 1][-width:] == rows[n][-width:]:
        return f"tie at LIMIT {n}: sort key {rows[n][-width:]}"
    return None


def validate(questions: list[dict]) -> tuple[list[str], list[dict]]:
    errors: list[str] = []
    results: list[dict] = []
    ids = Counter(q.get("id") for q in questions)
    errors += [f"duplicate id {i}" for i, c in ids.items() if c > 1]
    texts = Counter(q.get("question", "").strip().lower() for q in questions)
    errors += [f"duplicate question text: {t!r}" for t, c in texts.items() if c > 1]
    for q in questions:
        qid = q.get("id", "?")
        missing = [f for f in REQUIRED if f not in q]
        if missing:
            errors.append(f"{qid}: missing fields {missing}")
            continue
        if q["level"] not in LEVELS:
            errors.append(f"{qid}: unknown level {q['level']}")
        try:
            tree = check_sql(q["gold_sql"])
            rows = execute_readonly(DB, q["gold_sql"])
        except Exception as e:  # noqa: BLE001 - report every failure, keep going
            errors.append(f"{qid}: gold SQL failed: {type(e).__name__}: {e}")
            continue
        if not rows:
            errors.append(f"{qid}: gold SQL returned no rows")
        elif all(v is None for row in rows for v in row):
            errors.append(f"{qid}: gold SQL returned only NULLs")
        if q["order_matters"] and tree.args.get("order") is None:
            errors.append(f"{qid}: order_matters is true but the gold SQL has no ORDER BY")
        tie = limit_tie(q["gold_sql"])
        if tie:
            errors.append(f"{qid}: {tie}")
        results.append({**q, "n_rows": len(rows), "preview": rows[:5]})
    return errors, results


def fmt(v: object) -> str:
    return f"{v:,.4f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def write_review(results: list[dict], path: Path) -> None:
    lines = ["# Olist benchmark: review sheet", "",
             "Generated by `data_prep/validate_olist_questions.py`. For each question, check that the gold SQL",
             "answers **exactly** what the question asks, and that the question is unambiguous.", ""]
    counts = Counter(r["level"] for r in results)
    lines.append("Counts: " + ", ".join(f"{lvl} {counts[lvl]}" for lvl in LEVELS) + f", total {len(results)}")
    for r in results:
        lines += ["", f"### {r['id']} ({r['level']}{', order matters' if r['order_matters'] else ''})",
                  f"**Q:** {r['question']}", "", "```sql", r["gold_sql"], "```",
                  f"{r['n_rows']} row(s): " + "; ".join("(" + ", ".join(fmt(v) for v in row) + ")"
                                                      for row in r["preview"])
                  + (" ..." if r["n_rows"] > 5 else "")]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def split(questions: list[dict]) -> tuple[list[dict], list[dict]]:
    rng = random.Random(SPLIT_SEED)
    dev, test = [], []
    for level in LEVELS:
        group = sorted((q for q in questions if q["level"] == level), key=lambda q: q["id"])
        rng.shuffle(group)
        k = round(len(group) / 3)
        dev += group[:k]
        test += group[k:]
    key = lambda q: (LEVELS.index(q["level"]), q["id"])  # noqa: E731
    return sorted(dev, key=key), sorted(test, key=key)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", action="store_true", help="write questions_dev.json and questions_test.json")
    args = ap.parse_args()
    if not DB.is_file():
        sys.exit("data/olist/olist_marts.db missing: run data_prep/build_olist_marts.py first")
    questions = json.loads(DRAFT.read_text(encoding="utf-8"))
    errors, results = validate(questions)
    write_review(results, OLIST / "questions_review.md")
    counts = Counter(q.get("level") for q in questions)
    print(f"{len(questions)} questions: " + ", ".join(f"{lvl} {counts[lvl]}" for lvl in LEVELS))
    print(f"review sheet: {OLIST / 'questions_review.md'}")
    if errors:
        print(f"\n{len(errors)} problem(s):")
        for e in errors:
            print("  - " + e)
        return 1
    print("all gold queries valid")
    if args.split:
        dev, test = split(questions)
        for name, part in (("questions_dev.json", dev), ("questions_test.json", test)):
            (OLIST / name).write_text(json.dumps(part, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"split: dev {len(dev)}, test {len(test)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
