"""Collect every results/<run>/summary.json into one markdown table (results/RESULTS.md).

README numbers are copied from this generated file, never typed by hand.

    python scripts/results_table.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pct(d: dict) -> str:
    return f"{100 * d['acc']:.1f} [{100 * d['ci95'][0]:.1f}, {100 * d['ci95'][1]:.1f}]"


def main() -> int:
    results = ROOT / "results"
    rows = []
    for f in sorted(results.glob("*/summary.json")):
        s = json.loads(f.read_text(encoding="utf-8"))
        c = s["config"]
        rows.append((c["dataset"], c["run_id"], c["model"], c["engine"], c.get("n_shots", 0), c["use_definitions"],
                     pct(s["ex_strict"]), s["ex_strict"]["n"], f"{100 * s['valid_sql_rate']:.1f}",
                     s["latency_s"]["mean"], s.get("cached_token_share")))
    if not rows:
        sys.exit("no results/*/summary.json found")
    lines = ["# All runs", "", "Generated by `scripts/results_table.py` from `results/*/summary.json`.", "",
             "| Dataset | Run | Model | Engine | Shots | Definitions | EX strict % [95% CI] | n | Valid SQL % "
             "| Mean latency s | Prefix-cache share |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows):
        lines.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    (results / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
